import { readFile, writeFile } from 'node:fs/promises';
const job = await readFile('scripts/remote/job.sh', 'utf8');
const manager = await readFile('scripts/remote/manage.py', 'utf8');
const content = `// Generated by scripts/embed-remote.ts. Edit scripts/remote/ instead.\nexport const JOB_SCRIPT = ${JSON.stringify(job)};\nexport const MANAGER_SCRIPT = ${JSON.stringify(manager)};\n`;
if (process.argv.includes('--check')) {
  if (await readFile('src/server/remote.generated.ts', 'utf8') !== content) throw new Error('Remote scripts changed. Run pnpm generate.');
} else await writeFile('src/server/remote.generated.ts', content);
